"""게이트 — 규칙 추출 결과를 보고 LLM 에스컬레이션 등급을 정한다.

왜 필요한가
-----------
규칙이 8항목을 확신 있게 잡은 사이트는 LLM 을 호출할 이유가 없다. 8,000건 전부를 호출하면
$139 이지만, 규칙이 통과한 건을 건너뛰면 실패한 건에만 비용이 든다. 게다가 이미지까지 보내는
진단은 더 비싸므로 정말 필요한 건에만 써야 한다.

3등급
-----
    통과      — 규칙 결과를 그대로 쓴다. LLM 호출 0회. 비용 $0
    검토필요  — 텍스트 + 규칙결과를 LLM 에 보낸다 (Tier 1). 건당 약 $0.017
    진단필요  — 스크린샷 + DOM 까지 보낸다 (Tier 2). 원인 진단 + override 생성

판정 기준은 파일럿 1·2회차 실측에서 나왔다:
  - 라벨 없는 값(주소·발행인)은 규칙이 구조적으로 놓친다 → 미검출은 검토 대상
  - 확신도 low 는 '라벨 없이 형식만 보고 추정' 이라는 뜻이다 → 검토 대상
  - 위치=기타 는 title 태그 폴백이라는 뜻이다 → 상·하단 게재 요건을 못 만족할 수 있다
  - 본문 0자·js_의심 은 텍스트가 아예 없다는 뜻이므로 텍스트 검토가 무의미하다 → 바로 진단
"""
from __future__ import annotations

from datetime import date

from .fields import REQUIRED_FIELDS

통과 = "통과"
검토필요 = "검토필요"
진단필요 = "진단필요"

# 미검출이 이 개수 이상이면 텍스트 검토를 건너뛰고 바로 진단으로 보낸다.
# 규칙이 절반 이상을 놓쳤다면 라벨 변형 문제가 아니라 영역 분리 실패일 가능성이 높다.
진단_미검출_임계 = 4


# 게이트A 통과 기준. 파일럿 1+2회차 23건 실측 통과율:
#   엄격 0% / 중간 26% / 느슨 35%
# 기본은 '중간' — 저확신은 LLM 호출을 생략해도 `확인필요=Y` 로 남아 사람 검수를 받는다.
# '느슨' 은 위치=기타(title 태그 폴백)를 통과시켜 상·하단 게재 요건 미충족을 놓칠 수 있다.
통과기준_엄격 = "엄격"
통과기준_중간 = "중간"
통과기준_느슨 = "느슨"
기본_통과기준 = 통과기준_중간


def evaluate(findings: dict, *, 접속결과: str = "가능", js_의심: bool = False,
             텍스트길이: dict | None = None, override_적용: bool = False,
             통과기준: str = 기본_통과기준, 기준일: date | None = None) -> dict:
    """규칙 추출 결과 → 등급 판정.

    Returns
    -------
    {"등급": 통과|검토필요|진단필요,
     "사유": [str, ...],            # 사람이 읽을 판정 근거
     "미해결항목": [str, ...],       # LLM 이 집중해야 할 항목
     "이미지필요": bool}
    """
    사유: list[str] = []
    미검출: list[str] = []
    저확신: list[str] = []
    위치기타: list[str] = []

    for f in REQUIRED_FIELDS:
        item = findings.get(f) or {}
        val = (item.get("값") or "").strip()
        if not val or val == "해당사항 없음":
            미검출.append(f)
            continue
        if (item.get("확신도") or "") == "low":
            저확신.append(f)
        # 발행연월일은 기사목록 표기가 정상이므로 위치=기타를 문제로 보지 않는다
        if (item.get("위치") or "") == "기타" and f != "발행연월일":
            위치기타.append(f)

    전체길이 = (텍스트길이 or {}).get("전체")

    # --- 진단필요(이미지) 는 '텍스트 자체가 없을 때' 만이다 ---
    # 텍스트가 있으면 무조건 Tier 1(텍스트 검토)을 먼저 거친다. 파일럿 2회차 실측에서
    # 미검출 4항목이던 30875 가 텍스트 검토만으로 3항목을 해결했다 — 미검출 개수를 근거로
    # 비싼 비전 호출로 보내면 낭비다. '잘 안 됐다' 는 판정은 검토 후에 한다(evaluate_after_review).
    if 접속결과 not in ("가능", "", None):
        사유.append(f"접속결과={접속결과} — 텍스트 확보 실패, 검토할 원문이 없다")
        return {"등급": 진단필요, "사유": 사유, "미해결항목": list(REQUIRED_FIELDS),
                "이미지필요": True}
    if 전체길이 is not None and 전체길이 < 300:
        사유.append(f"본문 {전체길이}자 — 검토할 원문이 사실상 없다(렌더링 의심)")
        return {"등급": 진단필요, "사유": 사유, "미해결항목": 미검출 or list(REQUIRED_FIELDS),
                "이미지필요": True}
    if js_의심 and not 미검출 == []:
        사유.append("js_의심 — requests 로 본문을 온전히 못 얻었을 가능성")
        return {"등급": 진단필요, "사유": 사유, "미해결항목": 미검출 or list(REQUIRED_FIELDS),
                "이미지필요": True}

    # ── 발행연월일 검증 대상 판정 (2026-08-14 지침 반영으로 축소) ────────────────
    #
    # 종전에는 확신도가 high 가 아니면 무조건 LLM 으로 보냈다. 근거는 "최신 기사 업데이트
    # 날짜인지 검증해야 한다" 였는데, **그 정의는 지침이 폐기했다** — 지침 R7 은 창간일·
    # 등록연월일도 발행연월일로 인정하므로 날짜의 성격을 가릴 이유가 없어졌다.
    # 그대로 두면 판정이 바뀌지도 않는 건에 LLM 을 쓴다(pilot3 실측 23건 중 5건 = 22%,
    # 8,000건 환산 약 1,700건).
    #
    # 지침 아래에서 규칙이 **실제로 못 가리는** 경우는 하나뿐이다:
    #   라벨 없는 날짜가 기준일(오늘)과 같을 때 — '투데이' 형 시계일 수 있다.
    #   (지침 R7-2 의 유일한 제외. 라벨이 붙어 있으면 fields._today_widget 이 이미 걸렀다.)
    # 그 외 — 명시 라벨·다른 날짜 라벨 대체·등록번호 병기·오늘이 아닌 날짜 — 는 결정적이다.
    발행 = findings.get("발행연월일") or {}
    발행값 = (발행.get("값") or "").strip()
    발행방법 = 발행.get("추출방법") or ""
    라벨없는_날짜 = ("라벨없음" in 발행방법) or ("기사 업로드" in 발행방법)
    오늘값 = (기준일 is None) or (발행값 == 기준일.isoformat())
    발행_미확정 = bool(발행값) and 라벨없는_날짜 and 오늘값
    if 발행_미확정:
        사유.append(f"발행연월일 {발행값} 이 라벨 없이 기준일과 같다 — "
                  f"'투데이' 형 시계 표기인지 LLM 문맥 판단 필요(지침 R7-2 제외 대상)")

    # --- 통과 판정 (기준별) ---
    차단 = {
        통과기준_엄격: bool(미검출 or 저확신 or 위치기타),
        통과기준_중간: bool(미검출 or 위치기타),
        통과기준_느슨: bool(미검출),
    }.get(통과기준, bool(미검출 or 위치기타)) or 발행_미확정
    if not 차단:
        보류 = (f" (저확신 {', '.join(저확신)} 은 확인필요로 남겨 사람이 검수한다)"
              if 저확신 else "")
        사유.append(f"필수 8항목 전부 게재 — 통과기준={통과기준}, LLM 호출 불필요{보류}")
        return {"등급": 통과, "사유": 사유, "미해결항목": [], "이미지필요": False}

    # --- 검토필요: 텍스트로 해결 가능한 범위 ---
    if 미검출:
        사유.append(f"미검출: {', '.join(미검출)}")
    if 저확신:
        사유.append(f"저확신(라벨없이 추정): {', '.join(저확신)}")
    if 위치기타:
        사유.append(f"위치=기타(title 폴백 의심): {', '.join(위치기타)}")
    if override_적용:
        사유.append("override 이미 적용됨 — 재진단 시 기존 override 검토 필요")
    return {"등급": 검토필요, "사유": 사유,
            "미해결항목": sorted(set(미검출) | set(저확신) | set(위치기타)),
            "이미지필요": False}


def evaluate_after_review(llm_findings: dict, *, 폐기항목: list[str] | None = None,
                          js_의심: bool = False, notes: str = "") -> dict:
    """Tier 1 텍스트 검토 결과 → 이미지 진단이 필요한가?

    '미검출' 자체는 실패가 아니다 — 매체가 정말 게재하지 않았을 수 있고, 그때는 이미지를
    봐도 결론이 같다. 이미지가 실제로 값을 더하는 경우는 정해져 있다:

      ① 근거검증 폐기 발생 — 모델이 근거 없는 값을 냈다. 신뢰할 수 없으니 다시 봐야 한다
      ② 위치=기타 잔존 — title 태그에서 가져왔다는 뜻. 실제로는 로고 **이미지** 일 가능성
      ③ 제호 미검출 — 제호를 표기하지 않는 매체는 없다. 텍스트에 없으면 이미지 표기다
      ④ 모델이 notes 에 '이미지' 를 언급 — 모델 스스로 이미지 표기를 의심했다
      ⑤ js_의심 — 텍스트가 온전하지 않다
    """
    폐기항목 = 폐기항목 or []
    사유: list[str] = []
    대상: set[str] = set(폐기항목)

    if 폐기항목:
        사유.append(f"근거검증 폐기: {', '.join(폐기항목)} — 근거 없는 값을 낸 항목")
    위치기타 = [f for f in REQUIRED_FIELDS
              if (llm_findings.get(f, {}) or {}).get("위치") == "기타" and f != "발행연월일"]
    if 위치기타:
        사유.append(f"위치=기타 잔존: {', '.join(위치기타)} — 로고 이미지 표기 의심")
        대상 |= set(위치기타)
    제호값 = ((llm_findings.get("제호") or {}).get("값") or "").strip()
    if not 제호값:
        사유.append("제호 미검출 — 제호를 표기하지 않는 매체는 없다. 이미지 표기로 봐야 한다")
        대상.add("제호")
    if "이미지" in (notes or ""):
        사유.append("모델이 notes 에 이미지 표기를 언급")
    if js_의심:
        사유.append("js_의심 — 텍스트가 온전하지 않다")

    if 사유:
        return {"등급": 진단필요, "사유": 사유,
                "미해결항목": sorted(대상) or list(REQUIRED_FIELDS), "이미지필요": True}
    return {"등급": 통과, "사유": ["텍스트 검토로 결론 도달 — 이미지 진단 불필요"],
            "미해결항목": [], "이미지필요": False}


def evaluate_row(row: dict, *, 기준일: date | None = None) -> dict:
    """CSV 한 행에서 바로 평가 (extract/verify CSV 후처리용)."""
    findings = {}
    for f in REQUIRED_FIELDS:
        findings[f] = {"값": row.get(f"{f}_게재값", ""),
                       "위치": row.get(f"{f}_위치", ""),
                       "확신도": row.get(f"{f}_확신도", "")}
    return evaluate(
        findings,
        접속결과=row.get("접속결과", "가능"),
        js_의심=str(row.get("js_의심", "")).strip().upper() in ("Y", "TRUE", "1"),
        기준일=기준일,
    )


__all__ = ["통과", "검토필요", "진단필요", "진단_미검출_임계", "evaluate", "evaluate_row"]

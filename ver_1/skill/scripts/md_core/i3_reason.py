"""지침 I-3 건이 **왜** 그렇게 됐는지 가른다.

지침 I 로직 3 은 "등록 URL 로 접속은 되는데 등록 매체명과 다르고 뉴스도 없다 →
홈페이지 없음 → 포털검색" 이다. 지침은 여기서 멈추지만, 실무에서는 그 다음이 갈린다:

    · 도메인을 남이 가져갔다      → 매체는 이사 갔을 수 있다. **포털검색 값어치 높음**
    · 점검·준비 중이다            → 매체가 살아 있다. **재방문이 답이지 검색이 아니다**
    · 뉴스와 무관한 사업체다       → 폐업 후 도메인 매각. 검색 값어치 보통
    · 빈 껍데기·서버 기본페이지     → 방치. 검색 값어치 보통

이 구분이 필요한 이유는 **포털검색이 비싸기 때문**이다. 실측 건당 $0.183(웹검색
서버도구 요금 포함)이고 I-4 122건에서 수확률은 2.5% 였다. 657건을 성격 구분 없이
전부 돌리면 $120 을 쓰고 대부분 '제호일치_미발견' 을 받는다.

판정은 **이미 저장된 본문**(work/{id}.json 의 title·상단·하단)만 읽는다. API 를 부르지
않고 사이트를 다시 방문하지도 않는다 — 지침 I 판정에 쓴 것과 같은 원본이다.

주의: 이 분류는 지침의 판정을 **바꾸지 않는다.** I-3 은 그대로 '홈페이지 없음' 이다.
후속 조치(검색할지·재방문할지)의 우선순위를 정하는 보조 정보다.
"""
from __future__ import annotations

import re

# ── 성격 이름 ────────────────────────────────────────────────────────────
도메인판매 = "도메인 판매·파킹"
호스팅만료 = "호스팅 만료·정지"
점검중 = "점검·준비 중"
운영중단 = "운영 중단 안내"
DNS오류 = "DNS·서버 응답 오류"
접근차단 = "접근 차단"
서버기본 = "서버 기본페이지"
빈껍데기 = "빈 껍데기"
불법도박 = "도박·성인 스팸 사이트"
타매체 = "다른 언론사 제호"
무관업종 = "뉴스와 무관한 사업체"

# ── 판별 패턴 ────────────────────────────────────────────────────────────
# 도메인 판매 중개·주차 서비스. 국내 DNSzi·sm.to 가 특히 많다(실측 상위).
_판매 = re.compile(
    r"domain\s*(for\s*sale|is\s*for\s*sale|acquisition)|이\s*도메인.{0,12}(판매|매물|구매)|"
    r"도메인\s*(판매|매매|거래|분양)|DNSzi|sm\.to|후이즈|가비아\s*도메인|"
    r"expireddomains|afternic|sedo|dan\.com|hugedomains|parkingcrew|bodis", re.I)

# 호스팅 계약 만료·정지 안내. 매체가 요금을 안 낸 것이지 도메인을 판 게 아니다.
_만료 = re.compile(
    r"이용\s*기간.{0,6}만료|서비스\s*(기간)?\s*(만료|종료|중지|정지)|계정.{0,4}(정지|만료)|"
    r"호스팅.{0,10}(만료|중지|정지|해지)|사용\s*기간이\s*(끝|만료)|"
    r"account\s*(suspended|expired)|this\s*site\s*is\s*suspended", re.I)

# 점검·준비 중 — 매체가 살아 있을 수 있다. 검색이 아니라 재방문 대상이다.
_점검 = re.compile(
    r"(서비스|시스템|서버|사이트|홈페이지).{0,6}점검|점검\s*(중|안내|작업)|"
    r"공사\s*중|준비\s*중|오픈\s*예정|재단장|리뉴얼\s*(중|작업|준비)|"
    r"under\s*construction|coming\s*soon|maintenance|temporarily\s*unavailable", re.I)

# 매체가 스스로 내건 중단·폐쇄 안내. 도메인을 놓은 것도, 요금 미납도 아니다.
_중단 = re.compile(
    r"사이트\s*(중단|폐쇄|종료)|서비스\s*(중단|폐쇄)|운영\s*(중단|중지|종료)|"
    r"폐간|휴간|더\s*이상\s*(운영|서비스)", re.I)

# 이름은 풀렸는데 서버가 응답하지 않는다 — 호스팅이 끊겼거나 서버가 내려갔다.
_dns = re.compile(
    r"dns\s*(resolution\s*)?(error|오류|실패)|서버를?\s*찾을\s*수\s*없|"
    r"연결할\s*수\s*없|this\s*site\s*can.?t\s*be\s*reached|"
    r"err_(name_not_resolved|connection)|502\s*bad\s*gateway|"
    r"503\s*service\s*unavailable|504\s*gateway", re.I)

_차단 = re.compile(
    r"\b403\b|forbidden|access\s*denied|접근.{0,6}(권한|거부|차단)|"
    r"권한이\s*없|차단된\s*(페이지|사이트)", re.I)

# 웹서버 기본 화면 — 아무것도 안 올린 상태다.
_기본 = re.compile(
    r"아파치\s*서버|apache\d*\s*(server)?|it\s*works|index\s*of\s*/|"
    r"welcome\s*to\s*(nginx|apache|iis)|여러분의\s*방문을\s*환영|"
    r"기본\s*페이지|default\s*(web\s*)?page|test\s*page", re.I)

# 만료 도메인을 채간 해외 도박·성인 스팸. 실측에서 긴 본문의 다수를 차지했다.
_도박 = re.compile(
    r"카지노|바카라|슬롯|토토|배팅|베팅|먹튀|casino|slot(s|\s*online)?|togel|"
    r"judi|taruhan|betting|sportsbook|poker|gacor|situs|bandar|"
    r"성인.{0,4}(사이트|영상)|야동|19금", re.I)

# 언론사 제호에 흔한 어미. 화면 제호가 이 꼴이면 **다른 매체가 들어왔거나 제호를 바꿨다** —
# 포털검색으로 진짜 홈페이지를 찾을 값어치가 가장 높은 부류다.
_매체어미 = re.compile(
    r"(뉴스|신문|일보|타임즈|타임스|times|news|저널|journal|미디어|media|"
    r"방송|프레스|press|데일리|daily|포스트|post|헤럴드|herald|경제|시사)", re.I)

# 검색 값어치 — 왜 이 등급인지는 각 분기 주석에 적었다.
값어치 = {
    타매체: "높음", 도메인판매: "높음", 호스팅만료: "높음",
    점검중: "낮음(재방문)", 운영중단: "낮음(폐간 확인)",
    DNS오류: "높음", 접근차단: "보통",
    불법도박: "보통", 무관업종: "보통", 서버기본: "보통", 빈껍데기: "보통",
}

후속 = {
    타매체: "포털검색 — 제호가 바뀌었거나 다른 매체가 들어왔다",
    도메인판매: "포털검색 — 도메인을 놓았으니 새 주소가 있을 수 있다",
    호스팅만료: "포털검색 — 요금 미납 상태. 다른 주소로 옮겼을 수 있다",
    점검중: "일정 기간 뒤 재방문 — 검색 대상이 아니다. 매체가 살아 있다",
    운영중단: "매체가 스스로 중단을 내걸었다 — 폐간 신고 여부를 등록기관에 확인",
    DNS오류: "포털검색 — 도메인은 남았으나 서버가 없다. 이사 갔을 개연성",
    접근차단: "재방문(UA·IP 차단 가능) 후에도 같으면 포털검색",
    불법도박: "포털검색 — 만료 도메인을 스팸이 채간 전형. 매체는 폐업 가능성",
    무관업종: "포털검색 — 폐업 후 도메인 매각 가능성",
    서버기본: "포털검색 — 방치된 서버",
    빈껍데기: "포털검색 — 내용이 없어 화면으로는 판단 불가",
}


def 판별(*, title: str = "", 상단: str = "", 하단: str = "",
        og_site_name: str = "", 본문길이: int = 0, 등록제호: str = "") -> dict:
    """→ {성격, 검색값어치, 후속조치, 근거}

    순서가 중요하다. 도박 스팸 페이지에도 '점검' 같은 단어가 섞여 있을 수 있으므로
    **확실한 표지부터** 본다: 도메인판매 → 만료 → 차단 → 점검 → 서버기본 → 도박.
    그 뒤에야 길이·제호 모양으로 가른다.
    """
    화면 = " ".join(x for x in (title, og_site_name, 상단, 하단) if x)
    짧은화면 = " ".join(x for x in (title, og_site_name) if x).strip()

    for 패턴, 성격 in ((_판매, 도메인판매), (_만료, 호스팅만료), (_중단, 운영중단),
                    (_dns, DNS오류), (_차단, 접근차단), (_점검, 점검중),
                    (_기본, 서버기본), (_도박, 불법도박)):
        m = 패턴.search(화면)
        if m:
            return _결과(성격, f"화면 문구 '{m.group(0)[:24]}'")

    if 본문길이 < 30:
        # 제호처럼 생긴 짧은 문자열만 있는 경우가 많다(예: 'sm.to', '오션타임즈').
        if 짧은화면 and _매체어미.search(짧은화면) and 짧은화면 != (등록제호 or ""):
            return _결과(타매체, f"화면 제호 '{짧은화면[:24]}' — 등록 제호와 다르다")
        # 본문이 짧아도 title 에 **실명**이 있으면 빈 껍데기가 아니라 그 사업체의 페이지다.
        # 예: '(주)한국재무심리연구소에 오신 것을 환영합니다!' — 26자지만 명백히 다른 회사다.
        if len(짧은화면) >= 8 and not _매체어미.search(짧은화면):
            return _결과(무관업종, f"화면명 '{짧은화면[:24]}' · 본문 {본문길이}자")
        return _결과(빈껍데기, f"본문 {본문길이}자")

    if 짧은화면 and _매체어미.search(짧은화면) and 짧은화면 != (등록제호 or ""):
        return _결과(타매체, f"화면 제호 '{짧은화면[:24]}' — 등록 제호와 다르다")

    return _결과(무관업종, f"본문 {본문길이}자 · 뉴스 표기 없음")


def _결과(성격: str, 근거: str) -> dict:
    return {"성격": 성격, "검색값어치": 값어치[성격],
            "후속조치": 후속[성격], "근거": 근거}

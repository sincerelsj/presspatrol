"""홈페이지 운영현황 판정 (지침 I).

왜 별도 단계인가
----------------
필요적 게재사항(지침 II)은 **홈페이지 '있음'** 인 매체만 점검한다. 종전 파이프라인에는 이
관문이 없었다 — `운영상태` 는 입력 xlsx 의 컬럼을 읽어 필터로만 썼고 계산하지 않았다.
그래서 ① 접속은 되는데 남의 사이트인 경우가 그대로 8항목 추출로 넘어갔고 ② 접속 불가 건이
`판정불가` 라는 지침에 없는 분류로 빠졌다.

지침 I 의 로직
--------------
    1) 접속 O · 매체명 **동일** (뉴스 유무 무관)      → 있음 / 진행
    2) 접속 O · 매체명 다름 · **뉴스 있음**           → 있음 / 진행
    3) 접속 O · 매체명 다름 · **뉴스 없음**           → 없음 / 포털검색
    4) 접속 시 **오류페이지**                         → 없음 / 포털검색

매체명 확인 기준(지침 비고): ① 홈페이지 상단 로고 ② 홈페이지 하단 정보.
뉴스 유무 판정(지침 비고): "카테고리 또는 제목에 '기사'/'뉴스'로 기재된 경우는 모두 뉴스로 봄."

수집 실패의 처리 (2026-08-14 결정)
----------------------------------
접속 불가·도메인 파킹·빈 응답·검색 미발견은 전부 **로직 4 → 없음** 이다. 지침에 `판정불가`
분류가 없으므로 이 경로로 흡수한다. **미준수(과태료 대상)로 찍지 않는다** — 게재 여부를
판단할 화면 자체가 없기 때문이다.
"""
from __future__ import annotations

import re

있음 = "있음"
없음 = "없음"

로직_동일 = "I-1"
로직_뉴스있음 = "I-2"
로직_뉴스없음 = "I-3"
로직_오류 = "I-4"

# 제호 정규화에서 떼어낼 법인격·군더더기. `(주)세종포스트` 와 `세종포스트` 는 같은 매체다.
_CORP = re.compile(r"\(\s*[주유사재]\s*\)|주식회사|유한회사|사단법인|재단법인|㈜|㈐")
_PUNCT = re.compile(r"[\s\-–—_.,·∙・|/\\'\"“”‘’()\[\]{}!?~]+")

# 지침 비고: "카테고리 또는 제목에 '기사'/'뉴스'로 기재된 경우는 모두 뉴스로 봄"
_NEWS_WORD = re.compile(r"뉴\s*스|기\s*사|news", re.I)
# 기사 상세로 가는 링크 — 텍스트에 '뉴스/기사' 가 없어도 기사를 싣고 있다는 증거다
_ARTICLE_HREF = re.compile(
    r"articleView|/news/|idxno=|/article/|view\.html|/view/|read\.php|/newsView", re.I)


def norm_title(s: str) -> str:
    return _PUNCT.sub("", _CORP.sub("", str(s or ""))).lower()


def title_matches(등록제호: str, *, 상단: str = "", 하단: str = "",
                  화면제호: str = "", title: str = "") -> tuple[bool, str]:
    """등록 제호가 화면의 매체명과 같은가 → (판정, 근거).

    확인 순서는 지침 비고 그대로 **① 상단 로고 → ② 하단 정보** 다.
    포함관계도 동일로 본다(`데일리안` ⊂ `데일리안뉴스`) — 애매한 판정은 매체에 유리하게 한다.
    """
    reg = norm_title(등록제호)
    if not reg or len(reg) < 2:
        return False, "등록 제호가 비어 있어 대조 불가"
    # 화면제호는 비전 진단이 로고 이미지에서 읽은 값일 수 있어 가장 직접적인 증거다
    for 이름, 값 in (("상단 로고", 상단), ("하단 정보", 하단),
                    ("추출된 제호", 화면제호), ("title 태그", title)):
        v = norm_title(값)
        if not v:
            continue
        if reg in v or (len(v) >= 2 and v in reg):
            return True, f"{이름} 기준 매체명 일치 ('{등록제호}')"
    return False, f"상단 로고·하단 정보 어디에서도 등록 제호 '{등록제호}' 를 찾지 못함"


def disclosure_match(등록정보: dict | None, zones: dict | None) -> tuple[list[str], str]:
    """화면에 등록부의 필요적 게재사항이 있는가 → (일치항목, 근거).

    왜 운영현황 판정에 이게 필요한가
    --------------------------------
    지침 I 는 매체명으로 동일성을 보라고 한다. 그런데 등록 제호와 화면 표기가 다른 매체가
    실재한다 — pilot3 30889 는 등록 제호가 `S.I.B불교인터넷신문사` 인데 화면은
    `SIB 불교교육방송` 이고, 하단에 '뉴스'·'기사' 문자열도 없다. 매체명과 뉴스만 보면
    **운영 중인 매체가 I-3(홈페이지 없음)으로 빠진다.** 과소 점검이다.

    그래서 지침 I 비고가 포털검색 후보 검증에 쓰는 바로 그 기준을 여기에도 쓴다 —
    게재사항 5항목 중 하나라도 등록부와 같으면 같은 매체로 본다. 지침의 다른 조항을
    그대로 옮긴 것이므로 자의적 완화가 아니고, 방향도 '매체에 유리하게' 다.
    반드시 `확인필요` 로 남겨 사람이 본다.
    """
    등록정보 = 등록정보 or {}
    z = zones or {}
    hay = _PUNCT.sub("", (z.get("상단", "") + "\n" + z.get("하단", "") + "\n"
                          + z.get("전체", "")))
    if not hay:
        return [], "화면 텍스트가 없어 대조 불가"
    hay_digits = re.sub(r"\D", "", hay)
    맞음, 상세 = [], []

    # 등록번호는 0 패딩 차이(`아00023`↔`아23`)가 흔하므로 양쪽을 정규화해 비교한다.
    # 문자열 포함으로 비교하면 `세종아23` 이 `세종아00023` 안에 없어서 전부 놓친다.
    want_reg = _norm_regnum_safe(등록정보.get("등록번호"))
    if want_reg and want_reg in {_norm_regnum_safe(t) for t in _REGNUM_IN_TEXT.findall(hay)}:
        맞음.append("등록번호")
        상세.append(f"등록번호 '{등록정보.get('등록번호')}'")
    for f, 최소, 자르기 in (("발행인", 2, 0), ("편집인", 2, 0),
                          ("발행소 주소", 8, 12), ("발행소 전화번호", 9, 0)):
        want = _PUNCT.sub("", str(등록정보.get(f) or ""))
        if f == "발행소 전화번호":
            want = re.sub(r"\D", "", want)
            if len(want) >= 최소 and want in hay_digits:
                맞음.append(f)
                상세.append(f"{f} '{등록정보.get(f)}'")
            continue
        if 자르기:
            want = want[:자르기]
        if len(want) >= 최소 and want in hay:
            맞음.append(f)
            상세.append(f"{f} '{등록정보.get(f)}'")
    if 맞음:
        return 맞음, "화면에서 등록부와 같은 게재사항 확인: " + ", ".join(상세)
    return [], "화면에서 등록부와 같은 게재사항을 하나도 찾지 못함"


# 화면 텍스트에서 등록번호처럼 보이는 것. 종별문자와 숫자가 **붙어 있고 3자리 이상** 인
# 것만 인정한다 — 공백을 허용하면 한글 문장의 '그러나 22' 가 걸린다(resolve_failed 실측).
_REGNUM_IN_TEXT = re.compile(r"(?:[가-힣]{2,6})?[아가나다라마바사자차카타파하]\d{3,6}")


def _norm_regnum_safe(v) -> str:
    """`세종 아00023` → `아23` 비교키. 0 패딩·공백과 **시·도 접두 유무**를 무시한다.

    지역명을 붙이면 안 된다 — 등록부는 `아00421` 로만 주는데(2026 배포본) 사이트 하단은
    `강원, 아00421` 로 적으므로 전부 어긋난다. field_rules.md 대조 규칙 3 과
    `registry.norm_regnum`(지역과 번호를 분리해 번호만 비교) 도 같은 방침이다.
    """
    m = re.search(r"([아가나다라마바사자차카타파하])\s*-?\s*0*(\d{1,6})", str(v or ""))
    return f"{m.group(1)}{int(m.group(2))}" if m else ""


def has_news(*, 상단: str = "", 전체: str = "", title: str = "", html: str = "") -> tuple[bool, str]:
    """뉴스를 제공하는 사이트인가 → (판정, 근거). 지침 비고의 넓은 기준을 그대로 쓴다."""
    for 이름, 값 in (("title", title), ("상단 카테고리·메뉴", 상단), ("본문", 전체)):
        m = _NEWS_WORD.search(값 or "")
        if m:
            return True, f"{이름}에 '{m.group(0)}' 표기 — 지침 비고상 뉴스로 본다"
    if html and _ARTICLE_HREF.search(html):
        return True, "기사 상세 링크 패턴 검출 — 기사를 싣고 있다"
    return False, "제목·카테고리·본문 어디에도 '뉴스'/'기사' 표기가 없고 기사 링크도 없음"


def evaluate(*, 접속결과: str, 등록제호: str = "", zones: dict | None = None,
             화면제호: str = "", 파킹의심: str = "", html: str = "",
             등록정보: dict | None = None) -> dict:
    """지침 I 의 4분기 판정.

    Returns
    -------
    {"운영현황": 있음|없음, "로직": "I-1"…, "사유": str,
     "매체명_동일": "Y"|"N"|"확인불가", "뉴스_있음": "Y"|"N"|"확인불가",
     "게재사항_일치": [str], "포털검색_필요": bool}
    """
    z = zones or {}
    빈결과 = {"매체명_동일": "확인불가", "뉴스_있음": "확인불가", "게재사항_일치": [],
            "포털검색_필요": True}
    if (파킹의심 or "").strip() == "Y":
        return {"운영현황": 없음, "로직": 로직_오류,
                "사유": "도메인 파킹·판매 페이지로 리다이렉트 — 사이트 부재. 지침 I-4", **빈결과}
    if 접속결과 not in ("가능", "", None):
        return {"운영현황": 없음, "로직": 로직_오류,
                "사유": f"등록 URL 접속 실패({접속결과}) — 오류페이지. 지침 I-4", **빈결과}

    동일, 제호근거 = title_matches(등록제호, 상단=z.get("상단", ""), 하단=z.get("하단", ""),
                                화면제호=화면제호, title=z.get("title", ""))
    if 동일:
        return {"운영현황": 있음, "로직": 로직_동일,
                "사유": f"{제호근거} — 뉴스 유무와 무관하게 진행. 지침 I-1",
                "매체명_동일": "Y", "뉴스_있음": "", "게재사항_일치": [],
                "포털검색_필요": False}

    뉴스, 뉴스근거 = has_news(상단=z.get("상단", ""), 전체=z.get("전체", ""),
                           title=z.get("title", ""), html=html)
    if 뉴스:
        return {"운영현황": 있음, "로직": 로직_뉴스있음,
                "사유": f"{제호근거}. 다만 {뉴스근거} — 지침 I-2 로 진행",
                "매체명_동일": "N", "뉴스_있음": "Y", "게재사항_일치": [],
                "포털검색_필요": False}

    # 매체명도 다르고 뉴스 표기도 없다. 여기서 바로 I-3 으로 버리면 **운영 중인 매체를
    # 놓친다** — 등록 제호와 화면 표기가 다르고 텍스트가 빈약한 사이트가 실재한다.
    # 지침 I 비고가 매체 동일성 확인에 쓰는 게재사항 5항목을 마지막 관문으로 한 번 더 본다.
    일치, 대조근거 = disclosure_match(등록정보, z)
    if 일치:
        return {"운영현황": 있음, "로직": 로직_뉴스있음,
                "사유": (f"{제호근거}. {뉴스근거}. 다만 {대조근거} — 같은 매체로 보고 진행. "
                       f"지침 I 비고(게재사항 5항목 중 1개 이상 동일) 적용. **사람 확인 필요**"),
                "매체명_동일": "N", "뉴스_있음": "N", "게재사항_일치": 일치,
                "포털검색_필요": False}
    return {"운영현황": 없음, "로직": 로직_뉴스없음,
            "사유": f"{제호근거}. {뉴스근거}. {대조근거} — 지침 I-3. 포털검색 필요",
            "매체명_동일": "N", "뉴스_있음": "N", "게재사항_일치": [],
            "포털검색_필요": True}


